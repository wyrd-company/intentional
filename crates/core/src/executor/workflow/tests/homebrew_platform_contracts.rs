    #[test]
    #[ignore = "run through task cargo-homebrew:compatibility"]
    fn cargo_homebrew_platform_contract_bsdtar_3_4_3_accepts_macos_archive() {
        let workspace = cargo_homebrew_platform_contract_workspace("bsdtar-positive");
        let step = cargo_homebrew_platform_contract_step(
            &workspace,
            "intentional_build_component_cargo_archive_macos_arm64",
        );
        let body = step["run"].as_str().expect("derived macOS body");
        let (output, archive) = cargo_homebrew_execute_bsdtar_body(&workspace, &step, body);
        assert!(
            output.status.success(),
            "macOS archive body failed under bsdtar 3.4.3: {}",
            String::from_utf8_lossy(&output.stderr)
        );
        let inspection = cargo_homebrew_inspect_bsdtar_archive(&workspace, &archive);
        assert!(
            inspection.status.success(),
            "bsdtar archive inspection failed: {}",
            String::from_utf8_lossy(&inspection.stderr)
        );
        let inspection = String::from_utf8(inspection.stdout).expect("archive report is UTF-8");
        let mut lines = inspection.lines();
        assert_eq!(lines.next(), Some("name=sample-tool"), "archive content assertion");
        assert_eq!(lines.next(), Some("mode=755"), "archive executable-mode assertion");
        assert_eq!(lines.next(), Some("epoch=0"), "archive timestamp assertion");
        let binary = step["env"]
            .as_mapping()
            .expect("macOS build environment")
            .iter()
            .find_map(|(key, value)| {
                key.as_str()
                    .filter(|key| key.ends_with("SUBJECT_IDENTITY"))
                    .and_then(|_| value.as_str())
            })
            .expect("derived binary identity");
        let execution = cargo_homebrew_execute_archived_binary(&workspace, &archive, binary);
        assert!(
            execution.status.success(),
            "archived binary failed: {}",
            String::from_utf8_lossy(&execution.stderr)
        );
        assert_eq!(
            String::from_utf8_lossy(&execution.stdout),
            "sample-tool 1.2.3\n",
            "archived binary assertion"
        );
    }

