// Product-shaped Cargo/Homebrew platform contract tests.

    fn cargo_homebrew_platform_contract_workspace(label: &str) -> Workspace {
        let workspace = rust_homebrew_workspace_with_package_path(
            label,
            "[package]\nname = \"sample-tool\"\nversion = \"1.2.3\"\nedition = \"2021\"\ndescription = \"Sample command line tool\"\nlicense = \"MIT\"\n",
            "command",
        );
        workspace
            .write(
                "Cargo.lock",
                "# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 4\n\n[[package]]\nname = \"sample-tool\"\nversion = \"1.2.3\"\n",
            )
            .write(
                "component/command/src/main.rs",
                "fn main() { println!(\"sample-tool 1.2.3\"); }\n",
            );
        workspace
    }

    fn cargo_homebrew_platform_contract_step(workspace: &Workspace, job: &str) -> Value {
        converge(workspace.root(), WorkflowRole::Publish);
        job_steps(&publish_jobs(workspace.root()), job)
            .into_iter()
            .find(|step| step["run"].is_string())
            .unwrap_or_else(|| panic!("{job} has an emitted build body"))
    }

    fn cargo_homebrew_write_executable(path: &Path, body: &str) {
        std::fs::write(path, body).unwrap_or_else(|error| panic!("write {}: {error}", path.display()));
        #[cfg(unix)]
        {
            use std::os::unix::fs::PermissionsExt;
            std::fs::set_permissions(path, std::fs::Permissions::from_mode(0o755))
                .unwrap_or_else(|error| panic!("make {} executable: {error}", path.display()));
        }
    }

    fn cargo_homebrew_resolved_environment(
        step: &Value,
        workspace_root: &str,
        runner_root: &str,
    ) -> BTreeMap<String, String> {
        step_environment(step)
            .into_iter()
            .map(|(key, value)| {
                (
                    key,
                    value
                        .replace("${{ github.workspace }}", workspace_root)
                        .replace("${{ runner.temp }}", runner_root),
                )
            })
            .collect()
    }

    fn cargo_homebrew_workspace_working_directory(
        workspace: &Workspace,
        step: &Value,
    ) -> PathBuf {
        let configuration = std::fs::read_to_string(workspace.root().join(".intentional/config.yml"))
            .expect("platform contract configuration is readable");
        let configuration: Value =
            serde_yaml::from_str(&configuration).expect("platform contract configuration parses");
        let release_units = configuration["release-units"]
            .as_mapping()
            .expect("platform contract configuration declares release units");
        let mut release_units = release_units.values();
        let release_unit = release_units
            .next()
            .expect("platform contract configuration declares one release unit");
        assert!(
            release_units.next().is_none(),
            "platform contract configuration selects one release unit"
        );
        let packages = release_unit["packages"]
            .as_mapping()
            .expect("platform contract release unit declares packages");
        let mut packages = packages.values();
        let package = packages
            .next()
            .expect("platform contract release unit declares one package");
        assert!(
            packages.next().is_none(),
            "platform contract release unit selects one package"
        );
        let configured_directory = workspace
            .root()
            .join(
                release_unit["path"]
                    .as_str()
                    .expect("platform contract release unit declares its path"),
            )
            .join(
                package["path"]
                    .as_str()
                    .expect("platform contract package declares its path"),
            );
        let working_directory = step["working-directory"]
            .as_str()
            .expect("parsed job declares its working directory");
        let execution_directory = workspace.root().join(working_directory);
        assert!(
            execution_directory.is_dir(),
            "emitted workspace working directory exists: {}",
            execution_directory.display()
        );
        assert_eq!(
            execution_directory
                .canonicalize()
                .expect("emitted workspace working directory resolves"),
            configured_directory
                .canonicalize()
                .expect("configured package working directory resolves"),
            "emitted Cargo archive working directory matches the configured package path"
        );
        execution_directory
    }

    fn cargo_homebrew_execute_workspace_body(
        workspace: &Workspace,
        step: &Value,
        body: &str,
    ) -> (std::process::Output, PathBuf) {
        let runner = workspace.root().join("workspace-contract-runner");
        let stubs = runner.join("stubs");
        std::fs::create_dir_all(&stubs).expect("workspace contract stub directory");
        cargo_homebrew_write_executable(
            &stubs.join("cross"),
            "#!/usr/bin/env bash\nset -euo pipefail\nexec cargo \"$@\"\n",
        );
        let environment = cargo_homebrew_resolved_environment(
            step,
            workspace.root().to_str().expect("UTF-8 workspace path"),
            runner.to_str().expect("UTF-8 runner path"),
        );
        let archive = runner.join(
            environment
                .iter()
                .find_map(|(key, value)| key.ends_with("ARCHIVE").then_some(value))
                .expect("derived archive name"),
        );
        let execution_directory = cargo_homebrew_workspace_working_directory(workspace, step);
        let mut command = std::process::Command::new("bash");
        command
            .args(["-c", body])
            .current_dir(execution_directory)
            .env("RUNNER_TEMP", &runner)
            .env("LC_ALL", "C")
            .env("PATH", format!("{}:{}", stubs.display(), std::env::var("PATH").unwrap_or_default()));
        for (key, value) in environment {
            command.env(key, value);
        }
        (command.output().expect("workspace platform body runs"), archive)
    }

    fn cargo_homebrew_gzip_mtime(archive: &[u8]) -> u32 {
        assert!(archive.len() >= 10, "gzip header is complete");
        assert_eq!(&archive[..3], &[0x1f, 0x8b, 0x08], "gzip header identifies DEFLATE");
        u32::from_le_bytes(
            archive[4..8]
                .try_into()
                .expect("gzip MTIME occupies four header bytes"),
        )
    }

    fn cargo_homebrew_run_archive_twice(
        label: &str,
        mut execute: impl FnMut() -> (std::process::Output, PathBuf),
    ) -> (Vec<u8>, Vec<u8>) {
        let (first_output, first_archive) = execute();
        assert!(
            first_output.status.success(),
            "{label} first archive run succeeds: {}",
            String::from_utf8_lossy(&first_output.stderr)
        );
        let first = std::fs::read(&first_archive)
            .unwrap_or_else(|error| panic!("read {}: {error}", first_archive.display()));

        std::thread::sleep(std::time::Duration::from_secs(2));

        let (second_output, second_archive) = execute();
        assert!(
            second_output.status.success(),
            "{label} second archive run succeeds: {}",
            String::from_utf8_lossy(&second_output.stderr)
        );
        let second = std::fs::read(&second_archive)
            .unwrap_or_else(|error| panic!("read {}: {error}", second_archive.display()));
        (first, second)
    }

    #[test]
    #[ignore = "run through task cargo-homebrew:compatibility"]
    fn cargo_homebrew_platform_contract_workspace_member_reads_workspace_root_target() {
        let workspace = cargo_homebrew_platform_contract_workspace("workspace-root-output");
        let step = cargo_homebrew_platform_contract_step(
            &workspace,
            "intentional_build_component_cargo_archive_linux_x86_64",
        );
        let environment = cargo_homebrew_resolved_environment(
            &step,
            workspace.root().to_str().expect("UTF-8 workspace path"),
            workspace
                .root()
                .join("workspace-contract-runner")
                .to_str()
                .expect("UTF-8 runner path"),
        );
        let target_directory = PathBuf::from(
            environment
                .get("CARGO_TARGET_DIR")
                .expect("parsed job declares Cargo output"),
        );
        assert_eq!(
            target_directory.parent(),
            Some(workspace.root().join("target").as_path()),
            "the parsed job owns a workspace-root target directory"
        );

        let body = step["run"].as_str().expect("derived workspace body");
        let (output, archive) = cargo_homebrew_execute_workspace_body(&workspace, &step, body);
        assert!(
            output.status.success(),
            "real Cargo workspace body failed: {}",
            String::from_utf8_lossy(&output.stderr)
        );
        assert!(
            target_directory
                .join("x86_64-unknown-linux-gnu/release/sample-tool")
                .is_file(),
            "real Cargo writes the workspace-root output consumed by the emitted body"
        );
        let listing = std::process::Command::new("tar")
            .args(["-tzf", archive.to_str().expect("UTF-8 archive path")])
            .output()
            .expect("workspace archive lists");
        assert!(listing.status.success());
        assert_eq!(
            String::from_utf8_lossy(&listing.stdout),
            "sample-tool\n",
            "the archive contains the binary read from the workspace-root target"
        );
    }

    #[test]
    #[ignore = "run through task cargo-homebrew:compatibility"]
    fn cargo_homebrew_platform_contract_gnu_gzip_stdin_mtime_is_zero() {
        let workspace = cargo_homebrew_platform_contract_workspace("gnu-gzip-mtime");
        let step = cargo_homebrew_platform_contract_step(
            &workspace,
            "intentional_build_component_cargo_archive_linux_x86_64",
        );
        let body = step["run"].as_str().expect("derived Linux body");
        let without_no_name = body.replacen("gzip -n", "gzip", 1);
        let (first_without_no_name, second_without_no_name) = cargo_homebrew_run_archive_twice(
            "GNU gzip without -n",
            || cargo_homebrew_execute_workspace_body(&workspace, &step, &without_no_name),
        );
        assert_eq!(
            cargo_homebrew_gzip_mtime(&first_without_no_name),
            0,
            "GNU gzip assigns MTIME zero to piped standard input without -n"
        );
        assert_eq!(
            first_without_no_name, second_without_no_name,
            "GNU gzip piped-standard-input bytes do not depend on -n"
        );

        let (first, second) = cargo_homebrew_run_archive_twice("emitted GNU gzip body", || {
            cargo_homebrew_execute_workspace_body(&workspace, &step, body)
        });
        assert_eq!(
            first, second,
            "emitted GNU gzip archive bytes are identical across runs"
        );
        assert_eq!(
            cargo_homebrew_gzip_mtime(&first),
            0,
            "emitted GNU gzip archive header MTIME is zero"
        );
    }

