    fn cargo_homebrew_bsdtar_image() -> &'static str {
        static IMAGE: std::sync::OnceLock<String> = std::sync::OnceLock::new();
        IMAGE.get_or_init(|| {
            let repository = Path::new(env!("CARGO_MANIFEST_DIR")).join("../..");
            let dockerfile = std::fs::read_to_string(
                repository.join("scripts/ci/cargo-homebrew-bsdtar.Dockerfile"),
            )
            .expect("bsdtar Dockerfile is readable");
            assert!(
                dockerfile.lines().any(|line| {
                    line == "FROM debian:11.11-slim@sha256:f313b4bd62667092a59b3a664d7d3ab8b5e65f41675f48e81455a15dc5abe792"
                }),
                "bsdtar provisioning base is digest pinned"
            );
            assert!(
                dockerfile.contains("libarchive-tools=3.4.3-2+deb11u4"),
                "bsdtar provisioning selects the executed libarchive package"
            );
            let output = std::process::Command::new("docker")
                .args([
                    "build",
                    "--quiet",
                    "--platform",
                    "linux/amd64",
                    "--file",
                    "scripts/ci/cargo-homebrew-bsdtar.Dockerfile",
                    ".",
                ])
                .current_dir(repository)
                .output()
                .expect("Docker builds the pinned bsdtar environment");
            assert!(
                output.status.success(),
                "pinned bsdtar image build failed: {}",
                String::from_utf8_lossy(&output.stderr)
            );
            String::from_utf8(output.stdout)
                .expect("Docker image identity is UTF-8")
                .trim()
                .to_owned()
        })
    }

    fn cargo_homebrew_execute_bsdtar_body(
        workspace: &Workspace,
        step: &Value,
        body: &str,
    ) -> (std::process::Output, PathBuf) {
        use std::os::unix::fs::MetadataExt;

        let runner = workspace.root().join("bsdtar-contract-runner");
        let stubs = runner.join("stubs");
        std::fs::create_dir_all(&stubs).expect("bsdtar contract stub directory");
        cargo_homebrew_write_executable(
            &stubs.join("cargo"),
            r#"#!/usr/bin/env bash
set -euo pipefail
target=""
binary=""
while [[ $# -gt 0 ]]; do
  case "$1" in
    --target) target="$2"; shift 2 ;;
    --bin) binary="$2"; shift 2 ;;
    *) shift ;;
  esac
done
test -n "$target"
test -n "$binary"
mkdir -p "${CARGO_TARGET_DIR}/${target}/release"
printf '#!/usr/bin/env bash\nprintf "%s 1.2.3\\n"\n' "$binary" > "${CARGO_TARGET_DIR}/${target}/release/${binary}"
"#,
        );
        cargo_homebrew_write_executable(
            &stubs.join("tar"),
            "#!/usr/bin/env bash\nexec /usr/bin/bsdtar \"$@\"\n",
        );
        let environment = cargo_homebrew_resolved_environment(step, "/workspace", "/runner");
        let archive_name = environment
            .iter()
            .find_map(|(key, value)| key.ends_with("ARCHIVE").then_some(value.clone()))
            .expect("derived macOS archive name");
        let workspace_working_directory =
            cargo_homebrew_workspace_working_directory(workspace, step);
        let relative_working_directory = workspace_working_directory
            .strip_prefix(workspace.root())
            .expect("working directory remains inside the mounted workspace");
        let container_working_directory =
            Path::new("/workspace").join(relative_working_directory);
        let metadata = std::fs::metadata(workspace.root()).expect("workspace metadata");
        let mut command = std::process::Command::new("docker");
        command.args([
            "run",
            "--rm",
            "--platform",
            "linux/amd64",
            "--user",
            &format!("{}:{}", metadata.uid(), metadata.gid()),
            "--volume",
            &format!("{}:/workspace", workspace.root().display()),
            "--volume",
            &format!("{}:/runner", runner.display()),
            "--volume",
            &format!("{}:/stubs:ro", stubs.display()),
            "--workdir",
            container_working_directory
                .to_str()
                .expect("UTF-8 container working directory"),
            "--env",
            "LC_ALL=C",
        ]);
        for (key, value) in environment {
            command.args(["--env", &format!("{key}={value}")]);
        }
        command
            .args([
                "--env",
                "PATH=/stubs:/usr/local/sbin:/usr/local/bin:/usr/sbin:/usr/bin:/sbin:/bin",
                "--env",
                "RUNNER_TEMP=/runner",
                cargo_homebrew_bsdtar_image(),
                "bash",
                "-c",
                body,
            ]);
        (
            command.output().expect("emitted body runs in bsdtar environment"),
            runner.join(archive_name),
        )
    }

    #[test]
    #[ignore = "run through task cargo-homebrew:compatibility"]
    fn cargo_homebrew_platform_contract_bsd_gzip_header_is_run_independent() {
        let workspace = cargo_homebrew_platform_contract_workspace("bsd-gzip-mtime");
        let step = cargo_homebrew_platform_contract_step(
            &workspace,
            "intentional_build_component_cargo_archive_macos_arm64",
        );
        let body = step["run"].as_str().expect("derived macOS body");

        // Positive control first: BSD gzip assigns wall time to piped standard
        // input without -n, so the harness must observe two different archives.
        let without_no_name = body.replacen("gzip -n", "gzip", 1);
        let (varying_first, varying_second) = cargo_homebrew_run_archive_twice(
            "BSD gzip positive control without -n",
            || cargo_homebrew_execute_bsdtar_body(&workspace, &step, &without_no_name),
        );
        assert_ne!(
            cargo_homebrew_gzip_mtime(&varying_first),
            cargo_homebrew_gzip_mtime(&varying_second),
            "BSD gzip positive control advances header MTIME"
        );
        assert_ne!(
            varying_first, varying_second,
            "BSD gzip positive control produces time-varying compressed bytes"
        );

        let (first, second) = cargo_homebrew_run_archive_twice("emitted BSD gzip body", || {
            cargo_homebrew_execute_bsdtar_body(&workspace, &step, body)
        });
        assert_eq!(
            first, second,
            "emitted BSD gzip archive bytes are identical across runs"
        );
        assert_eq!(
            cargo_homebrew_gzip_mtime(&first),
            0,
            "emitted BSD gzip archive header MTIME is zero"
        );
    }

    fn cargo_homebrew_inspect_bsdtar_archive(
        workspace: &Workspace,
        archive: &Path,
    ) -> std::process::Output {
        use std::os::unix::fs::MetadataExt;

        let runner = archive.parent().expect("archive directory");
        let metadata = std::fs::metadata(workspace.root()).expect("workspace metadata");
        std::process::Command::new("docker")
            .args([
                "run",
                "--rm",
                "--platform",
                "linux/amd64",
                "--user",
                &format!("{}:{}", metadata.uid(), metadata.gid()),
                "--volume",
                &format!("{}:/runner", runner.display()),
                "--env",
                "LC_ALL=C",
                "--env",
                &format!(
                    "ARCHIVE={}",
                    archive.file_name().expect("archive name").to_string_lossy()
                ),
                cargo_homebrew_bsdtar_image(),
                "bash",
                "-c",
                r#"set -euo pipefail
rm -rf /runner/inspect
mkdir /runner/inspect
bsdtar -xzf "/runner/${ARCHIVE}" -C /runner/inspect
set -- /runner/inspect/*
test "$#" -eq 1
printf 'name=%s\n' "$(basename "$1")"
printf 'mode=%s\n' "$(stat -c %a "$1")"
printf 'epoch=%s\n' "$(stat -c %Y "$1")"
"#,
            ])
            .output()
            .expect("bsdtar archive inspection runs")
    }

